@Composable
fun ApexTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    accent: AccentChoice = AccentChoice.OCEAN,
    content: @Composable () -> Unit,
) {
    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }
    val colors = if (darkTheme) apexDarkColors(accent) else apexLightColors(accent)
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? android.app.Activity)?.window ?: return@SideEffect
            WindowCompat.getInsetsController(window, view).apply {
                isAppearanceLightStatusBars = !darkTheme
                isAppearanceLightNavigationBars = !darkTheme
            }
        }
    }
    CompositionLocalProvider(LocalApexColors provides colors) {
        MaterialTheme(
            colorScheme = colors.toMaterialScheme(),
            typography = ApexTypography,
            content = content,
        )
    }
}

private fun ApexColors.toMaterialScheme() = if (isDark) {
    darkColorScheme(
        primary = primary,
        onPrimary = onPrimary,
        primaryContainer = primaryContainer,
        onPrimaryContainer = onPrimaryContainer,
        secondary = secondary,
        onSecondary = onSecondary,
        background = background,
        onBackground = textPrimary,
        surface = surface,
        onSurface = textPrimary,
        surfaceVariant = surfaceVariant,
        onSurfaceVariant = textSecondary,
        surfaceContainer = surfaceElevated,
        surfaceContainerHigh = surfaceElevated,
        surfaceContainerLow = surface,
        error = error,
        onError = onError,
        errorContainer = errorContainer,
        onErrorContainer = error,
        outline = divider,
        outlineVariant = divider,
        scrim = Color.Black,
    )
} else {
    lightColorScheme(
        primary = primary,
        onPrimary = onPrimary,
        primaryContainer = primaryContainer,
        onPrimaryContainer = onPrimaryContainer,
        secondary = secondary,
        onSecondary = onSecondary,
        background = background,
        onBackground = textPrimary,
        surface = surface,
        onSurface = textPrimary,
        surfaceVariant = surfaceVariant,
        onSurfaceVariant = textSecondary,
        surfaceContainer = surface,
        surfaceContainerHigh = surface,
        surfaceContainerLow = surface,
        error = error,
        onError = onError,
        errorContainer = errorContainer,
        onErrorContainer = error,
        outline = divider,
        outlineVariant = divider,
        scrim = Color.Black,
    )
}

